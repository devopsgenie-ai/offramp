def render_namespace(appspec: AppSpec, environment) -> str:
    lines = [BANNER]
    if environment.namespace is None:
        lines += [
            f"# offramp: unresolved gap "
            f"{gap_id('environment', environment.name, 'namespace')}",
            "#   Derived from the app name, which is itself unanswered.",
        ]
    return yaml_block(
        lines
        + [
            "apiVersion: v1",
            "kind: Namespace",
            "metadata:",
            f"  name: {namespace_of(appspec, environment)}",
            "  labels:",
            f"    app.kubernetes.io/part-of: {app_name(appspec)}",
        ]
    )


def render_overlay_kustomization(appspec: AppSpec, environment) -> str:
    lines = [
        BANNER,
        f"# Overlay: {environment.name}",
        "apiVersion: kustomize.config.k8s.io/v1beta1",
        "kind: Kustomization",
        f"namespace: {namespace_of(appspec, environment)}",
        "resources:",
        "  - ../../base",
        "  - namespace.yaml",
    ]
    registry = appspec.delivery.image_registry
    if registry is None:
        registry = PLACEHOLDER_REGISTRY.value
        lines += marker(
            PLACEHOLDER_REGISTRY,
            f"{registry} is not a registry. Replace it before applying.",
        )
    tag = appspec.delivery.image_tag
    if tag is None:
        tag = environment.name
        lines += [
            f"# offramp: unresolved gap {gap_id('delivery', 'image_tag')}",
            f"#   Using the environment name, so every build overwrites '{tag}'.",
        ]
    lines.append("images:")
    for service in sorted(appspec.services, key=lambda s: s.name):
        lines += [
            f"  - name: {service.name}",
            f"    newName: {registry}/{app_name(appspec)}/{service.name}",
            f"    newTag: {tag}",
        ]
    if environment.replicas:
        lines += ["patches:", "  - path: replicas.yaml"]
    return yaml_block(lines)


def render_replicas_patch(appspec: AppSpec, environment) -> str | None:
    if not environment.replicas:
        return None
    documents = []
    for name in sorted(environment.replicas):
        documents += [
            "---",
            "apiVersion: apps/v1",
            "kind: Deployment",
            "metadata:",
            f"  name: {name}",
            "spec:",
            f"  replicas: {environment.replicas[name]}",
        ]
    return yaml_block([BANNER] + documents[1:])


def render_applicationset(appspec: AppSpec) -> str:
    lines = [BANNER]
    repo = appspec.delivery.gitops_repo_url
    if repo is None:
        repo = PLACEHOLDER_REPO.value
        lines += marker(
            PLACEHOLDER_REPO,
            "ArgoCD cannot resolve this. Replace it with the git repository you",
            "commit this tree to.",
        )
    name = app_name(appspec)
    return yaml_block(
        lines
        + [
            "apiVersion: argoproj.io/v1alpha1",
            "kind: ApplicationSet",
            "metadata:",
            f"  name: {name}",
            "  namespace: argocd",
            "spec:",
            "  generators:",
            "    - git:",
            f"        repoURL: {repo}",
            "        revision: HEAD",
            "        directories:",
            "          - path: k8s/overlays/*",
            "  template:",
            "    metadata:",
            f"      name: '{name}-{{{{path.basename}}}}'",
            "    spec:",
            "      project: default",
            "      source:",
            f"        repoURL: {repo}",
            "        targetRevision: HEAD",
            "        path: '{{path}}'",
            "      destination:",
            f"        server: {appspec.delivery.target_cluster}",
            f"        namespace: '{name}-{{{{path.basename}}}}'",
            "      syncPolicy:",
            "        automated:",
            "          prune: true",
            "          selfHeal: true",
            "        syncOptions:",
            "          - CreateNamespace=false",
        ]
    )


def render_readme(appspec: AppSpec) -> str:
    """#14: where the output tree sits, which RFC-0001 never says.

    The RFC calls the tool a scaffolder of a deployment repository for a greenfield
    user, and separately has it emit a Dockerfile per service. Those want opposite
    things: a Dockerfile must be able to COPY application source, so it cannot live
    in a repository the source is not in. This file records the resolution.
    """
    services = sorted(appspec.services, key=lambda s: s.name)
    return yaml_block(
        [
            "# Generated by offramp",
            "",
            "Every file listed in `manifest.json` was written by a renderer from the",
            "AppSpec. Do not edit them: `verify` re-renders and diffs, and `render`",
            "refuses to overwrite a file whose hash has changed since the last run.",
            "Change the AppSpec, or answer the gap, and render again.",
            "",
            "## Where this tree lives",
            "",
            "It is rooted at your application repository, not in a separate deployment",
            "repository. The Dockerfiles need to COPY application source, and the",
            "frontend image additionally needs `services/frontend/nginx.conf` from this",
            "generated tree, so one build context has to contain both. That context is",
            "the repository root.",
            "",
            "```",
            *[
                f"docker build -f services/{s.name}/Dockerfile -t {s.name} ."
                for s in services
            ],
            "```",
            "",
            "ArgoCD watches this same repository; the ApplicationSet's `path` glob points",
            "at `k8s/overlays/*`.",
            "",
            "## Deploying a new build",
            "",
            "The image tag is a per-build fact, and this tree is a pure function of the",
            "AppSpec, so the tag reaches it the same way every other value does: as an",
            "answer. Do not edit `newTag` in the overlay -- `verify` will report it, and it",
            "is right to, because it cannot tell your pipeline apart from something that",
            "edited generated output it should not have.",
            "",
            "```",
            "scan.py  <repo> --out .offramp/scan --answers answers.json",
            "# write a one-entry plan setting delivery.image_tag to the SHA you just built",
            "apply.py plan.json --scan .offramp/scan --repo . --now \"$(date -Iseconds)\" \\",
            "         --answers answers.json --out answers.json \\",
            "         --accept-resolve delivery.image_tag --accepted-by ci",
            "scan.py  <repo> --out .offramp/scan --answers answers.json",
            "render.py .offramp/scan/appspec.json --out . --force",
            "git commit -am \"deploy <sha>\"",
            "```",
            "",
            "No model and no API key are involved. Answers written this way are marked",
            "`accepted_by: ci`, so a reviewer can still see which answers a person decided.",
            "",
            "## What is not here",
            "",
            "The gap report. It lives with the scan output, because a renderer is given",
            "the AppSpec and gaps are not in it. Read it before applying anything: until",
            "every blocking gap is answered this tree contains placeholders that are",
            "deliberately invalid.",
        ]
    )


