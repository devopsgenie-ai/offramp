"""Renderers: AppSpec -> {relative path: file content}. Pure functions.

SPIKE revision 2. Every function takes an AppSpec and returns strings. Nothing
reads the source repository (AGENTS.md §6), nothing reads the clock or the
environment (AGENTS.md §3), nothing writes a file. render.py does the writing.

Two rules from SPIKE.md are enforced structurally here:

  #13/#22  Every value a renderer supplies that the AppSpec did not carry goes
           through DEFAULTS and emits a `# offramp: unresolved gap <id>` marker
           naming the gap it stands in for. Revision 1 let renderer defaults
           silently substitute for undetected values, where no gap counted them
           and no truth.yaml compared against them.

  #7       Those markers are built with spec.gap_id() from names in the AppSpec,
           because a renderer is given the AppSpec and gaps are not in it. That is
           a real constraint on the id scheme and RFC-0001 does not state it.
           scripts/spike_check.sh asserts every id named in the tree exists in
           gaps.json, which makes both rules checkable rather than aspirational.

Placeholders for unanswered inputs are spelled REPLACE-ME-*, in uppercase where
the field permits it: an uppercase registry is not a valid image reference, so an
unanswered blocking gap fails at `docker pull` with a clear message rather than
resolving to something plausible. The app name is the exception -- it lands in
namespace and label positions that must stay DNS-1123 valid for the output to
validate at all -- so it is lowercase and greppable instead.
"""

from __future__ import annotations

import json
import shlex
from dataclasses import dataclass
from typing import Any

from spec import AppSpec, Service, gap_id


@dataclass(frozen=True)
class Default:
    """A value the renderer supplies, and the gap it stands in for."""

    value: Any
    gap: str


# The renderer's whole vocabulary of invented values. Nothing outside this table
# may put an undetected value into the output.
def default_python(service: Service) -> Default:
    return Default("3.11", gap_id("service", service.build.context, "runtime", "version"))


def default_node(service: Service) -> Default:
    return Default("20", gap_id("service", service.build.context, "runtime", "version"))


def default_port(service: Service) -> Default:
    # #3: the port of a service compiled to static assets. The only port in the
    # source is the CRA dev server's 3000, which is wrong for the container that
    # ships, so this belongs to the renderer that chose the web server.
    return Default(8080, gap_id("service", service.build.context, "ports"))


def default_probes(service: Service) -> Default:
    from spec import Probe

    port = default_port(service).value
    return Default(
        [
            Probe("liveness", "/", port, "http", 15, 20),
            Probe("readiness", "/", port, "http", 5, 10),
        ],
        gap_id("service", service.build.context, "probes"),
    )


PLACEHOLDER_NAME = Default("replace-me-app-name", gap_id("app", "name"))
PLACEHOLDER_REGISTRY = Default("REPLACE-ME-registry", gap_id("delivery", "image_registry"))
PLACEHOLDER_REPO = Default("REPLACE-ME-repo-url", gap_id("delivery", "gitops_repo_url"))

NGINX_IMAGE = "nginxinc/nginx-unprivileged:1.27-alpine"
BANNER = "# Generated by offramp. Edits here are overwritten; change the AppSpec instead."


def marker(default: Default, *notes: str) -> list[str]:
    return [f"# offramp: unresolved gap {default.gap}"] + [f"#   {note}" for note in notes]


def app_name(appspec: AppSpec) -> str:
    return appspec.name or PLACEHOLDER_NAME.value


def namespace_of(appspec: AppSpec, environment) -> str:
    return environment.namespace or f"{app_name(appspec)}-{environment.name}"


def serving_port(service: Service) -> int:
    return service.ports[0] if service.ports else default_port(service).value


def labels(appspec: AppSpec, service: Service) -> list[tuple[str, str]]:
    return sorted(
        {
            "app.kubernetes.io/name": service.name,
            "app.kubernetes.io/part-of": app_name(appspec),
        }.items()
    )


def secret_name(appspec: AppSpec, service: Service, key: str) -> str:
    for datastore in appspec.datastores:
        if key in datastore.env_keys and service.name in datastore.consumed_by:
            # #25: keyed on the datastore's own name, not its kind.
            return f"{app_name(appspec)}-{datastore.name}"
    return f"{app_name(appspec)}-{service.name}"


def config_name(service: Service) -> str:
    return f"{service.name}-config"


def yaml_block(lines: list[str]) -> str:
    return "\n".join(lines).rstrip() + "\n"


