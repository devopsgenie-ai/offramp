def render_tree(appspec: AppSpec) -> dict[str, str]:
    """AppSpec -> every file in the output tree, keyed by relative POSIX path."""
    files: dict[str, str] = {
        ".dockerignore": render_dockerignore(appspec),
        ".offramp/README.md": render_readme(appspec),
    }
    base_resources: list[str] = []

    for service in sorted(appspec.services, key=lambda s: s.name):
        files[f"services/{service.name}/Dockerfile"] = render_dockerfile(appspec, service)
        if service.build.output_dir:
            files[f"services/{service.name}/nginx.conf"] = render_nginx_conf(appspec, service)

        configmap = render_configmap(appspec, service)
        if configmap:
            name = f"{service.name}-configmap.yaml"
            files[f"k8s/base/{name}"] = configmap
            base_resources.append(name)

        name = f"{service.name}-deployment.yaml"
        files[f"k8s/base/{name}"] = render_deployment(appspec, service)
        base_resources.append(name)

        name = f"{service.name}-service.yaml"
        files[f"k8s/base/{name}"] = render_service(appspec, service)
        base_resources.append(name)

    if appspec.routes:
        files["k8s/base/ingress.yaml"] = render_ingress(appspec)
        base_resources.append("ingress.yaml")

    files["k8s/base/kustomization.yaml"] = render_base_kustomization(appspec, base_resources)

    for environment in sorted(appspec.environments, key=lambda e: e.name):
        prefix = f"k8s/overlays/{environment.name}"
        files[f"{prefix}/kustomization.yaml"] = render_overlay_kustomization(appspec, environment)
        files[f"{prefix}/namespace.yaml"] = render_namespace(appspec, environment)
        patch = render_replicas_patch(appspec, environment)
        if patch:
            files[f"{prefix}/replicas.yaml"] = patch

    files["gitops/applicationset.yaml"] = render_applicationset(appspec)
    return dict(sorted(files.items()))
