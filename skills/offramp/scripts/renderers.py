def render_dockerfile(appspec: AppSpec, service: Service) -> str:
    context = service.build.context
    header = [
        BANNER,
        f"# service: {service.name} ({service.role}, {service.runtime.language})",
        "#",
        "# Build context is the repository root, not the service directory: the frontend",
        "# image needs a generated file (nginx.conf) as well as application source, and",
        "# a Dockerfile cannot COPY from outside its context. See .offramp/README.md.",
        "#",
        f"#   docker build -f services/{service.name}/Dockerfile -t {service.name} .",
        "",
    ]
    body = (
        _static_dockerfile(appspec, service, context)
        if service.build.output_dir
        else _runtime_dockerfile(service, context)
    )
    return yaml_block(header + body)


def _runtime_dockerfile(service: Service, context: str) -> list[str]:
    lines: list[str] = []
    version = service.runtime.version
    if version is None:
        chosen = default_python(service)
        version = chosen.value
        lines += marker(chosen, f"No version is pinned in {context}/. Using {version}.")
    command = shlex.split(service.build.start_cmd or "")
    return lines + [
        f"FROM python:{version}-slim",
        "",
        "ENV PYTHONDONTWRITEBYTECODE=1 \\",
        "    PYTHONUNBUFFERED=1",
        "",
        "WORKDIR /app",
        "",
        f"COPY {context}/requirements.txt ./",
        f"RUN {service.build.install_cmd}",
        "",
        f"COPY {context}/ ./",
        "",
        "RUN useradd --system --uid 10001 --no-create-home app \\",
        "    && chown -R 10001:0 /app",
        "USER 10001",
        "",
        *[f"EXPOSE {port}" for port in service.ports],
        "",
        f"CMD {json.dumps(command)}",
    ]


def _static_dockerfile(appspec: AppSpec, service: Service, context: str) -> list[str]:
    lines: list[str] = []
    version = service.runtime.version
    if version is None:
        chosen = default_node(service)
        version = chosen.value
        lines += marker(chosen, f"No version is pinned in {context}/. Using {version}.")
    lines += [
        f"FROM node:{version}-alpine AS build",
        "",
        "WORKDIR /app",
        "",
        f"COPY {context}/package.json ./",
        f"RUN {service.build.install_cmd}",
        "",
        f"COPY {context}/ ./",
        "",
    ]
    # #29: derived from env, which is the single record of this fact. There is no
    # Build.args to fall out of step with it.
    for var in sorted(
        (v for v in service.env if v.binding == "build_arg"), key=lambda v: v.name
    ):
        if var.value is None:
            lines += [
                f"# offramp: unresolved gap "
                f"{gap_id('service', context, 'env', var.name, 'value')}"
            ]
        lines += [
            f"#   {var.name} is substituted into the JavaScript bundle at build time.",
            "#   Pass it with --build-arg; a ConfigMap cannot change it afterwards.",
            f"ARG {var.name}" + (f"={json.dumps(var.value)}" if var.value is not None else ""),
            f"ENV {var.name}=${var.name}",
            "",
        ]
    lines += [
        f"RUN {service.build.build_cmd}",
        "",
    ]
    if not service.ports:
        lines += marker(
            default_port(service),
            "The web server serving the compiled bundle, and its port, are offramp's",
            "choice: the application has neither.",
        )
    lines += [
        f"FROM {NGINX_IMAGE}",
        "",
        f"COPY --from=build /app/{service.build.output_dir} /usr/share/nginx/html",
        f"COPY services/{service.name}/nginx.conf /etc/nginx/conf.d/default.conf",
        "",
        f"EXPOSE {serving_port(service)}",
    ]
    return lines


def render_nginx_conf(appspec: AppSpec, service: Service) -> str:
    return yaml_block(
        [
            BANNER,
            "",
            "server {",
            f"    listen {serving_port(service)};",
            "    server_name _;",
            "    root /usr/share/nginx/html;",
            "",
            "    # Single-page app: unknown paths are routed by the client, not the server.",
            "    location / {",
            "        try_files $uri $uri/ /index.html;",
            "    }",
            "}",
        ]
    )


def render_dockerignore(appspec: AppSpec) -> str:
    return yaml_block(
        [
            BANNER,
            "# Build context is the repository root; keep these out of it.",
            "",
            ".git",
            ".offramp",
            "**/__pycache__",
            "**/node_modules",
            "**/.env",
            "**/build",
            "**/dist",
        ]
    )


