def render_configmap(appspec: AppSpec, service: Service) -> str | None:
    """Literal, non-secret runtime values.

    Only binding "runtime" appears here. A build_arg in a ConfigMap is the failure
    RFC-0001's EnvVar.binding exists to prevent: the value is already compiled into
    the bundle and the ConfigMap changes nothing.
    """
    entries = [
        var
        for var in service.env
        if var.binding == "runtime" and not var.sensitive and var.value is not None
    ]
    if not entries:
        return None
    lines = [
        BANNER,
        "apiVersion: v1",
        "kind: ConfigMap",
        "metadata:",
        f"  name: {config_name(service)}",
        "  labels:",
        *[f"    {key}: {value}" for key, value in labels(appspec, service)],
        "data:",
    ]
    for var in sorted(entries, key=lambda v: v.name):
        lines.append(f"  {var.name}: {json.dumps(var.value)}")
    return yaml_block(lines)


def _env_entries(appspec: AppSpec, service: Service) -> list[str]:
    lines: list[str] = []
    for var in sorted(service.env, key=lambda v: v.name):
        if var.binding != "runtime":
            continue
        # #4: the reference is chosen on `sensitive`, not on `source`. MONGO_URL is
        # datastore-sourced and a credential; under RFC-0001's single enum only one
        # of those could be recorded, and the secret rule keyed on the wrong one.
        if var.sensitive:
            lines += [
                f"            - name: {var.name}",
                "              valueFrom:",
                "                secretKeyRef:",
                f"                  name: {secret_name(appspec, service, var.name)}",
                f"                  key: {var.name}",
            ]
        elif var.value is not None:
            lines += [
                f"            - name: {var.name}",
                "              valueFrom:",
                "                configMapKeyRef:",
                f"                  name: {config_name(service)}",
                f"                  key: {var.name}",
            ]
    return lines


def _probes_for(appspec: AppSpec, service: Service) -> tuple[list, list[str]]:
    """-> (probes, marker lines). Supplies probes for a static service, under #22."""
    if service.probes:
        return service.probes, []
    if not service.build.output_dir:
        return [], []
    chosen = default_probes(service)
    return chosen.value, marker(
        chosen,
        "This service has no health endpoint of its own. The probes below ask the",
        "generated web server for / and pass as soon as the page is served, which",
        "does not prove the app can reach the API.",
    )


def render_deployment(appspec: AppSpec, service: Service) -> str:
    selector = labels(appspec, service)
    probes, probe_marker = _probes_for(appspec, service)
    ports = service.ports or [serving_port(service)]
    port_marker = [] if service.ports or not service.build.output_dir else marker(
        default_port(service), "The container port below is offramp's choice."
    )
    lines = [BANNER, *port_marker, *probe_marker]
    lines += [
        "apiVersion: apps/v1",
        "kind: Deployment",
        "metadata:",
        f"  name: {service.name}",
        "  labels:",
        *[f"    {key}: {value}" for key, value in selector],
        "spec:",
        f"  replicas: {service.replicas}",
        "  selector:",
        "    matchLabels:",
        *[f"      {key}: {value}" for key, value in selector],
        "  template:",
        "    metadata:",
        "      labels:",
        *[f"        {key}: {value}" for key, value in selector],
        "    spec:",
        "      securityContext:",
        "        runAsNonRoot: true",
        "      containers:",
        f"        - name: {service.name}",
        # Bare name: the overlay's images transformer supplies registry and tag.
        f"          image: {service.name}",
        "          # Correct only while the image tag is immutable, which is what",
        "          # delivery.image_tag asks you to guarantee. Against a moving tag this",
        "          # silently runs whatever a node already cached.",
        "          imagePullPolicy: IfNotPresent",
        "          ports:",
    ]
    for port in ports:
        lines += ["            - name: http", f"              containerPort: {port}"]
    env_lines = _env_entries(appspec, service)
    if env_lines:
        lines.append("          env:")
        lines += env_lines
    # #24: liveness and readiness are separate probes with separate timings.
    for probe in sorted(probes, key=lambda p: p.role):
        check = (
            ["            tcpSocket:", f"              port: {probe.port}"]
            if probe.kind == "tcp"
            else [
                "            httpGet:",
                f"              path: {probe.path}",
                f"              port: {probe.port}",
            ]
        )
        lines += [
            f"          {probe.role}Probe:",
            *check,
            f"            initialDelaySeconds: {probe.initial_delay_seconds}",
            f"            periodSeconds: {probe.period_seconds}",
        ]
    lines += [
        "          resources:",
        "            requests:",
        *[f"              {k}: {v}" for k, v in sorted(service.resources.requests.items())],
        "            limits:",
        *[f"              {k}: {v}" for k, v in sorted(service.resources.limits.items())],
        "          securityContext:",
        "            allowPrivilegeEscalation: false",
        "            readOnlyRootFilesystem: false",
        "            capabilities:",
        "              drop:",
        "                - ALL",
    ]
    return yaml_block(lines)


def render_service(appspec: AppSpec, service: Service) -> str:
    selector = labels(appspec, service)
    lines = [
        BANNER,
        "apiVersion: v1",
        "kind: Service",
        "metadata:",
        f"  name: {service.name}",
        "  labels:",
        *[f"    {key}: {value}" for key, value in selector],
        "spec:",
        "  type: ClusterIP",
        "  selector:",
        *[f"    {key}: {value}" for key, value in selector],
        "  ports:",
    ]
    for port in service.ports or [serving_port(service)]:
        lines += [
            "    - name: http",
            f"      port: {port}",
            "      targetPort: http",
            "      protocol: TCP",
        ]
    return yaml_block(lines)


def render_ingress(appspec: AppSpec) -> str:
    lines = [BANNER]
    if all(route.host is None for route in appspec.routes):
        lines += [
            f"# offramp: unresolved gap {gap_id('route', 'host')}",
            "#   No hostname is set, so this rule matches any host that reaches the",
            "#   ingress controller and no certificate can be issued.",
        ]
    if appspec.delivery.ingress_class is None:
        lines += [
            f"# offramp: unresolved gap {gap_id('delivery', 'ingress_class')}",
            "#   No ingressClassName is set, so the cluster's default IngressClass is used.",
        ]
    lines += [
        "apiVersion: networking.k8s.io/v1",
        "kind: Ingress",
        "metadata:",
        f"  name: {app_name(appspec)}",
        "  labels:",
        f"    app.kubernetes.io/part-of: {app_name(appspec)}",
        "spec:",
    ]
    if appspec.delivery.ingress_class:
        lines.append(f"  ingressClassName: {appspec.delivery.ingress_class}")
    hosts = sorted({route.host for route in appspec.routes if route.host})
    lines.append("  rules:")
    # Longest path first: a controller matching in order must see /api before /, or
    # every API call is served the frontend bundle.
    ordered = sorted(appspec.routes, key=lambda r: (-len(r.path), r.path))
    for host in hosts or [None]:
        lines.append(f"    - host: {host}" if host else "    - http:")
        if host:
            lines.append("      http:")
        indent = "        " if host else "        "
        lines.append(f"{indent}paths:")
        for route in ordered:
            if host and route.host != host:
                continue
            lines += [
                f"{indent}  - path: {route.path}",
                f"{indent}    pathType: Prefix",
                f"{indent}    backend:",
                f"{indent}      service:",
                f"{indent}        name: {route.service}",
                f"{indent}        port:",
            ]
            # #3: a null port means "wire to the Service's named port", so the
            # detector never has to know a number that belongs to the renderer.
            if route.port is None:
                lines.append(f"{indent}          name: http")
            else:
                lines.append(f"{indent}          number: {route.port}")
    if appspec.routes and any(route.tls for route in appspec.routes) and hosts:
        lines += ["  tls:", "    - hosts:"]
        lines += [f"        - {host}" for host in hosts]
        lines.append(f"      secretName: {app_name(appspec)}-tls")
    return yaml_block(lines)


def render_base_kustomization(appspec: AppSpec, resources: list[str]) -> str:
    return yaml_block(
        [
            BANNER,
            "apiVersion: kustomize.config.k8s.io/v1beta1",
            "kind: Kustomization",
            "resources:",
            *[f"  - {name}" for name in sorted(resources)],
        ]
    )


